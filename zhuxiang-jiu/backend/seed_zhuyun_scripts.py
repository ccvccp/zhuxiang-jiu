async def main() -> None:
    svc = KnowledgeService()
    ok, fail = [], []
    for category, question, answer, keywords in SCRIPTS:
        try:
            entry = await svc.create_entry(
                question=question, answer=answer,
                category=category, keywords=keywords,
                source="manual", created_by=1)
            eid = entry["id"]
            await svc.review_entry(eid, approve=True,
                                   reviewer_id=1, reason="")
            await svc.publish_entry(eid, publisher_id=1)
            ok.append((eid, category, question[:18]))
        except ValueError as e:
            fail.append((question[:18], str(e)[:60]))
    print("PUBLISHED %d / FAILED %d" % (len(ok), len(fail)))
    for q, err in fail:
        print("  FAIL: %s <- %s" % (q, err))
    if not fail:
        for eid, cat, q in ok:
            print("  #%d [%s] %s" % (eid, cat, q))
    # 检索冒烟(redis 持久态下验证真实召回; 重复项 FAIL 属幂等重跑)
    for probe in ("收到酒瓶子破了", "送爸爸什么酒好", "小孩能喝吗"):
        r = await svc.rag_answer(probe, provider="rule")
        print("SMOKE [%s] mode=%s conf=%.2f" % (
            probe, r.get("mode"), r.get("confidence", 0)))


if __name__ == "__main__":
    asyncio.run(main())
