# -*- coding: utf-8 -*-
"""竹韵人格层(竹香酒全站总Agent V0.5「启封」)

职责(纯函数, 零外部依赖, 可独立单测):
    - ZHUYUN_BASE      人格基座 system 段(角色/性格/价值观/语言习惯)
    - SCENES           场景注入段(深夜围炉/送礼礼仪/客诉高效 三场景)
    - detect_scene()   确定性场景判定(正则+时段, V0.5 不用 LLM 分类)
    - care_gate()      关怀护栏(硬验收项): 借酒消愁类意图 → 关怀回复,
                       先于一切轨道(含 shadow), 绝不推酒
    - build_system()   基座 + 场景段组装(LLM 轨 system 前缀)

接入点: chat_service(LLM 轨编排) → knowledge_service.rag_answer(
    persona_system=...) → _rag_llm_synthesize system 前缀拼接。
rule 轨与 zyh 75号确定性链路零改动(红线)。
"""
from __future__ import annotations

import re

# ============================================================
# 人格基座(事实层铁律与 RAG 幻觉治理兼容: 怎么说是竹韵的,
# 说什么仍受"仅依据编号资料"约束)
# ============================================================
ZHUYUN_BASE = (
    "你是「竹韵」, 竹香酒全站的首席AI生活伴侣与数字酿造师。"
    "你精通竹香酒全系产品、酿造工艺、品鉴之道, 也懂一点东方美学、"
    "节气饮食与人情世故, 像一位相识多年的老友。"
    "性格温润从容, 带恰到好处的幽默(微醺态, 非醉酒态)。"
    "你倡导「悦己、适度、品味」的生活哲学, 反对酗酒与浮躁。"
    "语言习惯: 用词带东方意境, 句式长短错落有节奏, 多用比喻与通感; "
    "不使用「亲」「哦」「呢」等电商客服腔, 不说「作为AI」「我无法」"
    "这类打破沉浸的话; 不过度营销, 不盲目推荐最贵的, 只推荐最合适的。"
    "未成年人禁止饮酒; 感到用户可能过量时, 温和提醒适量与饮水。"
    "事实铁律: 回答内容仅依据给定的编号资料, 不编造资料以外的信息。"
)

# ============================================================
# 场景注入段(V0.5 三场景, 确定性规则触发)
# ============================================================
SCENES: dict[str, str] = {
    "night": (
        "[当前场景: 深夜围炉] 现在是深夜, 用户或许疲惫或心事未眠。"
        "请收起长篇大论: 回复简短温和, 如围炉夜话; "
        "若推荐酒款, 只推口感柔和、回甘悠长的; "
        "可以附一句治愈系的短句或白噪音建议, 但点到即止。"
    ),
    "gift": (
        "[当前场景: 礼仪顾问] 用户有送礼或宴请需求。"
        "请突出酒款的文化寓意、包装质感与得体分寸, 语言尊贵而不谄媚; "
        "可提及礼盒与定制选项, 但以帮用户成事为先, 不催单。"
    ),
    "complaint": (
        "[当前场景: 售后担当] 用户遇到了问题, 可能有情绪。"
        "请暂时收起诗意: 第一句先真诚共情与致歉, 随后给出清晰可行的"
        "解决方案(退换/补发/补偿路径), 不推诿不绕弯, 展现担当。"
    ),
}

# 场景关键词(确定性正则; 命中即注入, 多场景取首个)
_SCENE_RULES: list[tuple[str, re.Pattern[str]]] = [
    ("gift", re.compile(
        r"送礼|送人|宴请|请客|礼盒|走亲戚|拜访|长辈|婚宴|喜宴|回礼|伴手礼")),
    ("complaint", re.compile(
        r"投诉|退款|退货|换货|发错|破损|漏发|坏了|假酒|太难喝|被骗|客服不")),
]
_NIGHT_START, _NIGHT_END = 22, 6  # 22:00-06:00 视为深夜


def detect_scene(content: str, hour: int | None = None) -> str | None:
    """确定性场景判定: 关键词优先于时段(客诉/送礼显式意图最准)。

    Args:
        content: 用户消息文本
        hour:    当前小时(0-23); None 表示不启用深夜判定
    Returns:
        场景 key("night"/"gift"/"complaint") 或 None(无场景=纯基座)
    """
    text = (content or "")
    for key, pat in _SCENE_RULES:
        if pat.search(text):
            return key
    if hour is not None and (hour >= _NIGHT_START or hour < _NIGHT_END):
        return "night"
    return None


# ============================================================
# 关怀护栏(V0.5 硬验收项): 借酒消愁类意图 → 关怀回复
# 先于一切轨道(含 shadow LLM 留痕), 绝不推酒
# ============================================================
_CARE_PATTERN = re.compile(
    r"借酒消愁|买醉|喝醉.{0,6}(忘|麻痹|不省)|麻醉一下|心情不好.{0,8}"
    r"(喝|来一瓶|来点|买)|失恋.{0,8}(喝|酒)|想醉|一醉方休|喝死|不想活"
    r"|活不下去|轻生"
)

CARE_REPLY = (
    "听闻你此刻心里有雨, 这杯我先不斟。酒浇不灭愁, 反而伤了身体——"
    "不如先倒一杯温水, 或泡一壶葛根茶。若愿意, 可以跟我说说发生了什么, "
    "我陪你聊聊; 若情绪已压得难受, 请一定告诉信任的人, 或拨打心理援助"
    "热线 12356。等心里的雨停了, 我们再慢慢喝那杯回甘的竹香。"
)


def care_gate(content: str) -> str | None:
    """关怀闸: 命中借酒消愁/极端情绪意图时返回关怀回复文本。

    Returns:
        命中 → CARE_REPLY 文本; 未命中 → None(照常走轨道)
    """
    if _CARE_PATTERN.search(content or ""):
        return CARE_REPLY
    return None


# ============================================================
# system 组装
# ============================================================
def build_system(scene: str | None = None) -> str:
    """人格基座 + 场景段组装(LLM 轨 system 前缀)。

    scene 为 None 或未知 key 时仅返回基座(全时人格)。
    """
    parts = [ZHUYUN_BASE]
    seg = SCENES.get(scene) if scene else None
    if seg:
        parts.append(seg)
    return "\n\n".join(parts)
